export function messagingStale(
  sampledAt: string,
  cacheSeconds: number,
  now: number,
) {
  const stamp = Date.parse(sampledAt);
  // Two missed five-second refreshes plus the advertised management cache.
  return (
    !Number.isFinite(stamp) ||
    now - stamp > (10 + Math.max(0, cacheSeconds)) * 1000
  );
}

