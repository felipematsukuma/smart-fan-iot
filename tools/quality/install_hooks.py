"""Install repo-local hooks without pre-commit's temporary hiding of unstaged edits."""

import shlex
import subprocess
import sys
from pathlib import Path

from tooling import ROOT

MARKER = "# smartfan: all-files hooks preserve the working tree"


def main():
    hooks = Path(
        subprocess.check_output(
            ["git", "rev-parse", "--git-path", "hooks"], cwd=ROOT, text=True
        ).strip()
    )
    if not hooks.is_absolute():
        hooks = ROOT / hooks
    hooks.mkdir(parents=True, exist_ok=True)
    executable = shlex.quote(Path(sys.executable).as_posix())
    for name in ("pre-commit", "commit-msg"):
        target = hooks / name
        if target.exists():
            existing = target.read_text(encoding="utf-8")
            if (
                MARKER not in existing
                and "File generated by pre-commit" not in existing
            ):
                raise RuntimeError("Existing custom hook must be preserved")
    for name in ("pre-commit", "commit-msg"):
        arguments = (
            '--hook-stage commit-msg --commit-msg-filename "$1"'
            if name == "commit-msg"
            else "--hook-stage pre-commit"
        )
        target = hooks / name
        target.write_text(
            f"#!/bin/sh\n{MARKER}\nexec {executable} -m pre_commit run --all-files {arguments}\n",
            encoding="utf-8",
            newline="\n",
        )
        target.chmod(0o755)
    print("Installed all-files hooks; unstaged edits remain visible and unchanged.")


if __name__ == "__main__":
    main()
